/**
 * Writes measured prop dimensions from the built libraries into the game.
 *
 * Collider sizes were previously hand-typed next to each placement, so they
 * drifted whenever a library was rebuilt. Generating them means a collider can
 * never disagree with the mesh it stands for.
 *
 *   node tools/write-manifest.mjs
 */
import { NodeIO, getBounds } from "@gltf-transform/core";
import { ALL_EXTENSIONS } from "@gltf-transform/extensions";
import { MeshoptDecoder } from "meshoptimizer";
import { writeFile } from "node:fs/promises";

await MeshoptDecoder.ready;
const io = new NodeIO()
  .registerExtensions(ALL_EXTENSIONS)
  .registerDependencies({ "meshopt.decoder": MeshoptDecoder });

const LIBRARIES = ["props.glb", "furniture.glb"];
const sizes = new Map();

for (const file of LIBRARIES) {
  const doc = await io.read(`apps/web/public/models/${file}`);
  for (const node of doc.getRoot().listScenes()[0].listChildren()) {
    if (!node.getMesh()) continue;
    const name = node.getName();
    if (sizes.has(name)) throw new Error(`duplicate prop id across libraries: ${name}`);
    const b = getBounds(node);
    sizes.set(name, [0, 1, 2].map((i) => +(b.max[i] - b.min[i]).toFixed(4)));
  }
}

const entries = [...sizes].sort(([a], [b]) => a.localeCompare(b));
const body = entries
  .map(([id, size]) => `  "${id}": [${size.join(", ")}],`)
  .join("\n");

await writeFile(
  "apps/web/game/data/propSizes.generated.ts",
  `// Generated by tools/write-manifest.mjs. Do not edit.\n` +
    `// Measured from the built prop libraries, so a collider can never\n` +
    `// disagree with the mesh it stands for.\n` +
    `import type { Vec3 } from "../types";\n\n` +
    `export const PROP_SIZES = {\n${body}\n} as const satisfies Record<string, Vec3>;\n\n` +
    `export type PropId = keyof typeof PROP_SIZES;\n`,
);

console.log(`wrote ${entries.length} prop sizes:`);
for (const [id, size] of entries) {
  console.log(`  ${id.padEnd(16)} ${size.map((v) => v.toFixed(2)).join(" x ")} m`);
}
